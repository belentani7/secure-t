#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const coursesRoot = path.join(root, "campus", "cursos");
const output = path.join(root, "client", "src", "data", "campus.generated.ts");

const PROGRAM_ORDER = [
  "ciber-ofensiva",
  "ciber-defensiva",
  "ia-aplicada-segura",
  "gobernanza-compliance",
];

function section(text, heading) {
  const lines = text.split(/\r?\n/);
  const start = lines.findIndex(line =>
    line.trim().toLowerCase().startsWith(`## ${heading.toLowerCase()}`),
  );
  if (start === -1) return "";
  const body = [];
  for (const line of lines.slice(start + 1)) {
    if (/^##\s/.test(line)) break;
    body.push(line);
  }
  return body.join("\n").trim();
}

function bullets(text) {
  return text
    .split(/\r?\n/)
    .map(line => line.trim())
    .filter(line => line.startsWith("- "))
    .map(line => line.slice(2).trim())
    .filter(Boolean);
}

function firstParagraph(text) {
  return text
    .split(/\r?\n\s*\r?\n/)
    .map(part => part.trim())
    .find(part => part && !part.startsWith("#") && !part.startsWith(">"))
    ?.replace(/\s+/g, " ")
    .slice(0, 240) ?? "";
}

function markdownLinks(text) {
  const links = [];
  for (const match of text.matchAll(/\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/g)) {
    links.push({ label: match[1].trim(), url: match[2] });
  }
  return links;
}

function readCourse(slug) {
  const dir = path.join(coursesRoot, slug);
  const syllabus = readFileSync(path.join(dir, "syllabus.md"), "utf8");
  const title = syllabus.match(/^#\s+(.+)$/m)?.[1]?.trim() ?? slug;
  const hours = Number(syllabus.match(/(\d+)\s*horas/i)?.[1] ?? 0);
  const description = section(syllabus, "Descripcion") || section(syllabus, "DescripciÃ³n");
  const objectives = bullets(section(syllabus, "Objetivos de aprendizaje"));
  const assessment = bullets(section(syllabus, "Evaluacion estilo Harvard"))
    .concat(bullets(section(syllabus, "EvaluaciÃ³n estilo Harvard")));

  const weekFiles = readdirSync(dir)
    .filter(name => /^semana-\d+\.md$/.test(name))
    .sort((a, b) => a.localeCompare(b, "en", { numeric: true }));

  const weeks = weekFiles.map(file => {
    const number = Number(file.match(/semana-(\d+)/)?.[1] ?? 0);
    const text = readFileSync(path.join(dir, file), "utf8");
    const rawTitle = text.match(/^#\s+(.+)$/m)?.[1]?.trim() ?? file;
    const weekTitle = rawTitle.replace(/^Semana\s+\d+\s*[:Â·-]\s*/i, "").trim();
    const learning = bullets(section(text, "Objetivos de aprendizaje"));
    const objective =
      learning[0] ||
      firstParagraph(section(text, "Objetivo de la semana")) ||
      firstParagraph(text) ||
      "Objetivo disponible en el material completo.";
    return {
      number,
      title: weekTitle,
      objective,
      href: `campus/full/cursos/${slug}/${file}`,
    };
  });

  const labText = readFileSync(path.join(dir, "laboratorio.md"), "utf8");
  const labTitle = labText.match(/^#\s+(.+)$/m)?.[1]?.trim() ?? "Laboratorio guiado";
  const labIntro = firstParagraph(labText);

  const resourcesText = readFileSync(path.join(dir, "recursos.md"), "utf8");
  const links = markdownLinks(resourcesText).filter(link =>
    /github\.com|openlibrary\.org|wikipedia\.org|arxiv\.org|nist\.gov|owasp\.org|khanacademy\.org/i.test(
      link.url,
    ),
  );
  const resources = [...new Map(links.map(link => [link.url, link])).values()].slice(0, 8);

  return {
    slug,
    title,
    hours,
    language: "ES",
    description,
    objectives: objectives.slice(0, 6),
    assessment: assessment.slice(0, 6),
    lab: {
      title: labTitle.replace(/^Lab guiado:\s*/i, ""),
      intro: labIntro,
      href: `campus/full/cursos/${slug}/laboratorio.md`,
    },
    weeks,
    links: {
      course: `campus/full/cursos/${slug}/index.html`,
      syllabus: `campus/full/cursos/${slug}/syllabus.md`,
      quiz: `campus/full/cursos/${slug}/quiz.json`,
      rubric: `campus/full/cursos/${slug}/rubrica.md`,
      exam: `campus/full/cursos/${slug}/examen.md`,
      glossary: `campus/full/cursos/${slug}/glosario.md`,
      cheatsheet: `campus/full/cursos/${slug}/chuleta.md`,
      resources: `campus/full/cursos/${slug}/recursos.md`,
    },
    resources,
  };
}

const available = readdirSync(coursesRoot, { withFileTypes: true })
  .filter(entry => entry.isDirectory())
  .map(entry => entry.name);
const ordered = [
  ...PROGRAM_ORDER.filter(slug => available.includes(slug)),
  ...available.filter(slug => !PROGRAM_ORDER.includes(slug)).sort(),
];
const programs = ordered.map(readCourse);

const header = `// Generated by scripts/generate-campus-data.mjs from campus/cursos/*.
// Do not edit by hand: run \`node scripts/generate-campus-data.mjs\`.

export type CampusWeek = {
  number: number;
  title: string;
  objective: string;
  href: string;
};

export type CampusResource = { label: string; url: string };

export type CampusProgram = {
  slug: string;
  title: string;
  hours: number;
  language: string;
  description: string;
  objectives: string[];
  assessment: string[];
  lab: { title: string; intro: string; href: string };
  weeks: CampusWeek[];
  links: {
    course: string;
    syllabus: string;
    quiz: string;
    rubric: string;
    exam: string;
    glossary: string;
    cheatsheet: string;
    resources: string;
  };
  resources: CampusResource[];
};

export const CAMPUS_PROGRAMS: CampusProgram[] = `;

mkdirSync(path.dirname(output), { recursive: true });
writeFileSync(output, `${header}${JSON.stringify(programs, null, 2)};\n`, "utf8");

const weeks = programs.reduce((total, program) => total + program.weeks.length, 0);
console.log(
  `campus.generated.ts: ${programs.length} programs, ${weeks} weeks, ` +
    `${programs.reduce((total, program) => total + program.resources.length, 0)} resources`,
);

