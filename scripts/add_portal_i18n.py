def load_locale(lang: str) -> dict:
    path = LOCALES_DIR / f"{lang}.json"
    return json.loads(path.read_text(encoding="utf-8"))


def save_locale(lang: str, data: dict):
    path = LOCALES_DIR / f"{lang}.json"
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main():
    print("Adding portal i18n keys to all 9 locales...")
    for lang in LANGS:
        locale = load_locale(lang)
        added = 0
        for key, translations in PORTAL_KEYS.items():
            if key not in locale:
                locale[key] = translations[lang]
                added += 1
        if added:
            save_locale(lang, locale)
            print(f"  {lang}.json: +{added} keys")
        else:
            print(f"  {lang}.json: already up to date")
    print("Done!")


if __name__ == "__main__":
    main()